  /^(제품|상품|용역|서비스|기타|그밖|그외|기타등|제품매출|상품매출|용역매출|기타매출|서비스매출|기타사업|기타부문|기타사업부문|기타수익|기타매출액|임대|임대수익|수수료|합계|계|매출|매출액|주요제품|소분류|중분류|대분류)$/;

// 계약 목록 — 무슨 계약을 맺었나지 어디서 버느냐가 아니다.
//   명신산업   용역계약 · 상표권 사용 계약
//   덕양에너젠  계약 A · 계약 B · 계약 C · 계약 D
const 계약표 = /계약$|^계약[A-Z가-힣]$/;

/**
 * 라벨이 상장사 이름이면 거래처·종속회사 표다.
 *
 * ㈜ 나 Co. 가 안 붙은 이름은 꼴로 가릴 수 없다. 테마에 실린 회사 이름을
 * 그대로 견준다.
 *   에이치디현대미포  한화오션 · HD현대중공업 · HD현대삼호 · 삼성중공업
 *   자이에스앤디      LG에너지솔루션 · 기타
 */
const 상장사 = (() => {
  try {
    const t = JSON.parse(fs.readFileSync("src/data/themes.json", "utf8"));
    return new Set(t.themes.flatMap((x) => x.stocks).map((s) => 눌러(s.name)).filter((n) => n.length >= 3));
  } catch { return new Set(); }
})();

/**
 * 이 라벨들이 매출 구성 표인가 — 아니면 그 까닭을 돌려준다.
 *
 * 조각 수도 함께 본다. 「본사」 나 회사 이름이 한 줄만 껴도 조각이 셋 이하면
 * 법인별 표다 — 대동전자가 「태국 75.5% · 본사 24.5%」 였다.
 */
export function 매출표아님(labels, 조각수 = labels.length) {
  const 라벨 = labels.map(눌러);
  const 날것 = labels.map((x) => 실체풀기(x));
  const 몇 = (re) => 라벨.filter((x) => re.test(x)).length;
  if (몇(주식표) >= 2) return "주식 종류";
  if (몇(종속표) >= 2) return "종속·별도";
  if (몇(지역표) >= 2) return "지역별";
  if (날것.some((x) => 정관표.test(x))) return "사업목적";
  if (몇(손익표) >= 2) return "손익계산서";
  if (라벨.some((x) => 매입표.test(x))) return "매입";
  if (날것.filter((x) => 회사이름.test(x)).length >= 2) return "회사 이름";
  if (라벨.some((x) => 평가사.test(x))) return "신용평가";
  if (라벨.some((x) => 연구비표.test(x))) return "연구개발비";
  if (라벨.some((x) => 분류표.test(x))) return "산업분류";
  if (라벨.some((x) => 거래처표.test(x))) return "거래처";
  if (몇(자산표) >= 2) return "유형자산";
  if (몇(금융표) >= 2) return "금융·차입처";
  if (몇(채권표) >= 2) return "채권";
  if (몇(지재권표) >= 2) return "지식재산권";
  if (몇(환율표) >= 2) return "환율";
  if (조각수 <= 3 && (몇(종속표) >= 1 || 몇(지역표) >= 1)) return "법인·지역별(조각 셋 이하)";
  if (조각수 <= 3 && 날것.some((x) => 회사이름.test(x))) return "회사 이름(조각 셋 이하)";
  if (라벨.filter((x) => 계약표.test(x)).length >= 2) return "계약 목록";
  // 인증 현황 표 — 무엇을 땄나지 어디서 버느냐가 아니다.
  //   바이브컴퍼니  GS 인증 · SP 인증 (01-26-전-002) · SP 인증 (01-18-전-015)
  if (라벨.filter((x) => /인증$/.test(x)).length >= 2) return "인증 현황";
  const 상장사수 = 라벨.filter((x) => 상장사.has(x)).length;
  if (상장사수 >= 2) return "상장사 이름";
  if (조각수 <= 3 && 상장사수 >= 1) return "상장사 이름(조각 셋 이하)";
  // 국책과제 목록은 이름이 길다. 사업부문을 열네 글자로 적는 회사는 없다.
  //   웨이비스  방산혁신기업 100 기술개발 전용지원사업 · 창의형융합연구사업
  //   STX엔진  선상 CO2 포집 및 처리 기술 개발 · LNG엔진 메탄슬립 후처리 시스템 개발
  //
  // 한글이 여섯 자 넘게 든 것만 센다. 영문 부문명은 원래 길다 — 길이만 보면
  // 두산밥캣(Compact Equipment·Material Handling)과 SK케미칼(Green
  // Chemicals Biz.)까지 걷어 낸다.
  const 긴것 = 라벨.filter((x) => x.length >= 14 && (x.match(/[가-힣]/g) ?? []).length >= 6);
  if (긴것.length >= 2) return "과제 목록";
  return null;
}
