// 매출 표가 아닌 표를 가리는 규칙 — 한 곳에 모아 둔다.
//
// ── 왜 옮겼나 ─────────────────────────────────────────────
// 이 규칙이 화면 쪽(build-profile.mjs)에만 있었다. 뽑는 쪽(collect-segments)은
// 「조각의 합이 매출액과 맞나」 만 봤는데, 거래처별·지역별 매출 표도 합은
// 맞는다. 그래서 그런 표를 집고 거기서 멈췄다.
//
// 손해는 두 겹이었다.
//   집은 표가 화면에서 걸러져 원형이 안 선다              257종목
//   그중 204는 반기보고서였다 — 엉뚱한 표를 집는 바람에
//   사업보고서로 되돌아가 제대로 된 표를 찾을 기회를 잃었다
//
// 이제 뽑는 쪽이 이 규칙으로 먼저 걸러 다음 표·다음 보고서를 본다. 화면 쪽은
// 그대로 한 번 더 본다 — 이미 받아 둔 옛 자료에는 엉뚱한 표가 남아 있다.
