export const 머리글 = /^(제품명|품목|품명|구분|항목|사업부문|부문|종류|매출유형|유형|비고|매출현황|매출액현황|출유형|매출유형및품목|연결기준|별도기준|연결|별도|연도|회계연도|기간|년도)$/;
