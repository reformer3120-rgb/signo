// 한 문장짜리 사업 설명에서 "무엇을 파는가" 만 뽑아 낱말로 만든다.
//
// ── 왜 ─────────────────────────────────────────────────────
// 화면에 "제지(인쇄용지)를 생산하는 한솔그룹 계열사다." 라고 적혀 있으면
// 읽어야 뜻이 잡힌다. 종목이 수십 개 깔린 목록에서는 아무도 읽지 않는다.
// 알고 싶은 것은 무엇을 팔아 돈을 버는가 하나이므로 그것만 남긴다.
//
//   제지(인쇄용지)를 생산하는 한솔그룹 계열사다.  →  제지 · 인쇄용지
//   고속버스 운송업을 영위하는 기업이다.          →  고속버스 운송
//   자동차용 내장재(원단·시트커버링)를 생산한다.   →  자동차용 내장재 · 원단 · 시트커버링
//
// ── 어떻게 ─────────────────────────────────────────────────
// 한국어는 목적어가 서술어 앞에 온다. "…을/를 생산한다" 의 앞이 곧 품목이다.
// 그 자리를 잘라 내고 가운뎃점·쉼표로 쪼개면 그대로 낱말이 된다.
//
// 괄호는 두 가지로 쓰인다 — 품목을 더 밝히는 것과 회사 이름을 적는 것이다.
//   위생용지(화장지 등)      품목이다
//   채용정보 플랫폼(사람인)   회사 이름이다
// 종목명과 겹치면 회사 이름으로 보고 버린다.

/** 자사가 무엇을 한다는 서술어 — 이 앞이 품목이다 */
const 서술어 =
  // "겸영·겸업" 은 뺐다. 곁다리로 한다는 말이라 그 목적어는 주력이 아니다 —
  // "신기술사업금융업을 겸영하는 IT보안기업" 에서 알고 싶은 것은 IT보안이다.
  "생산|제조|개발|공급|제공|판매|영위|운영|수행|서비스|재배|유통|수입|수출|가공|시공|" +
  "건설|출시|납품|양산|취급|보유|설계|제작|시행|임대|전개|담당|수주|구축|조립|정제|사육|도급|" +
  "트레이딩|출판|투자|보증|중개|운용|보급";

/** 한 항목이 이보다 길면 쪼갠다. 이보다 짧으면 통째로 두는 편이 읽기 낫다 */
const 길이한도 = 18;

/** 품목이 될 수 없는 말 — 회사를 가리키는 일반명사 */
const 회사말 =
  /^(기업|회사|계열사|그룹|법인|업체|전문기업|전문업체|제조사|생산업체|지주회사|자회사|종속회사|상장사)$/;

/** 낱말 뒤에 붙어 뜻을 흐리는 꼬리 */
const 꼬리 = /\s*(등|외|류|중심|기반|위주|관련|전문)$/;

/**
 * 품목이 아닌 것. 문장에는 사업 말고도 목적어가 있다 —
 * "…타이어를 제조해 … 고수익을 낸다", "…건설사로, 워크아웃(재무구조개선)
 * 절차를 진행한 이력이 있다" 같은 대목이 그대로 품목으로 올라왔다.
 */
// 문장 조각이 그대로 올라온 것 — 낱말이 아니라 말꼬리다.
// "사육을 통한 종란 생산과 중추의 육성", "그 외에 축산관련 기타매출" 같은 것들.
const 어색한말 =
  /(을|를|이|가|에|의)\s(통한|따른|의한|대한|위한)|^(그|이|본|해당|위|아래|통한|따른|의한|대한|위한|외에|기타|및|또는)(\s|$)|^\S+(하는|되는|있는|하며|이며|해)\s/;

const 불용어 =
  /^(고수익|수익|매출|실적|이익|점유율|경쟁력|시장|사업|절차|이력|관심|지분|경영권|재무구조개선|워크아웃|구조조정|영업|성장|투자|자금|계약|주식|배당|사업부|부문|제품|서비스|솔루션|시스템|플랫폼|기술|사업다각화)$/;

const 정리 = (s) =>
  s
    .replace(/\s+/g, " ")
    .replace(/^[\s,·및]+|[\s,·및]+$/g, "")
    // "IT 기술 기반 솔루션 사업" → "IT 기술 기반 솔루션", "고속버스 운송업" → "고속버스 운송"
    .replace(/\s*사업$/, "")
    .replace(/(?<=[가-힣])업$/, "")
    .replace(꼬리, "")
    .trim();

/**
 * 괄호를 뗀다. 안의 것이 품목이면 따로 돌려주고, 회사 이름이면 버린다.
 * @returns {{ 몸통: string, 괄호: string[] }}
 */
function 괄호떼기(s, 종목명) {
  const 괄호 = [];
  // 괄호를 지운 자리에 공백을 남기면 조사가 뜬다 —
  // "철강재(냉연강판)의 표면처리" 가 "철강재 의 표면처리" 가 됐다. 붙여서 지운다.
  const 몸통 = s.replace(/[(（]([^)）]{1,40})[)）]/g, (_, inner) => {
    for (const p of inner.split(/[·,/]|\s+또는\s+/)) {
      const w = 정리(p);
      if (!w || w.length < 2) continue;
      // 종목명이 통째로 들어 있으면 회사 이름이다 — 카페24(카페24), 사람인(사람인)
      if (종목명 && (w === 종목명 || 종목명.includes(w) || w.includes(종목명))) continue;
      if (회사말.test(w)) continue;
      if (불용어.test(w)) continue;
      괄호.push(w);
    }
    return "";
  });
  return { 몸통, 괄호 };
}

/**
 * "…을/를 <서술어>" 앞의 목적어를 모두 걷는다.
 * 한 문장에 둘 이상 있을 수 있다 — "A 를 생산하고 B 를 판매한다".
 */
function 목적어들(문장) {
  const out = [];
  // 가운뎃점은 목적어 안에 있는 것이다 — "광통신 케이블·솔루션을 생산한다".
  // 여기서 끊으면 앞이 통째로 날아간다(그래서 옵티시스가 "솔루션" 만 남았다).
  // 목적어와 서술어 사이에 부사가 끼기도 한다 — "…등을 함께 영위하는".
  const re = new RegExp(`([^.,;]{2,60}?)(?:을|를)\\s*(?:\\S{1,4}\\s+)?(?:${서술어})`, "g");
  for (const m of 문장.matchAll(re)) out.push(m[1]);
  if (out.length) return out;

  // 서술어 없이 명사로 끝나는 문장도 많다. 그때는 "무엇 + 무슨 회사" 꼴이라
  // 앞의 명사구가 곧 품목이다.
  //   "자동차용 커넥터 전문기업이다."   "신발 OEM 생산업체다."
  //   "코로나19 진단키트로 유명한 체외진단 전문기업으로, …"
  const 명사끝 =
    /([^.,;]{2,40}?)\s*(?:전문기업|전문업체|생산업체|제조업체|제조사|기업|업체|회사|계열사|바이오텍|은행|리츠|상사|펀드|증권사|보험사|재보험사|보증기관|건설사)(?:이)?(?:다|로|으로|이며|이고)/g;
  for (const m of 문장.matchAll(명사끝)) out.push(m[1]);
  return out;
}

/**
 * 목적어 한 덩이를 항목으로 만든다.
 *
 * 짧으면 통째로 둔다 — "온라인 쇼핑몰 구축·운영 플랫폼" 을 가운뎃점에서 끊으면
 * "구축" 과 "운영 플랫폼" 이 되어 뜻이 무너진다. 한 줄에 들어갈 만큼 길면
 * 그때 끊는다.
 */
function 쪼개기(덩이) {
  const 하나 = 정리(덩이);
  const 쓸만한가 = (w) => w.length >= 2 && w.length <= 길이한도 && !회사말.test(w) && !불용어.test(w) && !어색한말.test(w);
  if (쓸만한가(하나)) return [하나];
  const 조각 = 하나
    .split(/[·,]|\s+및\s+|\s+과\s+|\s+와\s+|\s+등\s+|\//)
    .map(정리)
    .filter(쓸만한가);
  if (조각.length) return 조각;
  // 그래도 길면 머리말을 덜어 내고 끝(핵심 명사) 쪽을 남긴다
  const 말 = 하나.split(" ");
  for (let i = 1; i < 말.length; i++) {
    const w = 정리(말.slice(i).join(" "));
    if (쓸만한가(w)) return [w];
  }
  return [];
}

/**
 * 규칙 낱말(tags)을 다듬는다.
 * 사전 낱말은 판정을 위해 서술어까지 붙여 둔 것이 있다 — "식품을 제조",
 * "메모리 반도체를 생산". 화면에는 명사만 있으면 된다.
 */
export function 낱말다듬기(tag) {
  const w = 정리(
    String(tag)
      .replace(new RegExp(`(을|를)\\s*(${서술어}).*$`), "")
      .replace(/\s*사업$/, "")
      .replace(/\s*업$/, ""),
  );
  if (!w || w.length < 2 || 회사말.test(w)) return null;
  return w;
}

/**
 * 문장과 규칙 낱말에서 품목을 뽑는다.
 *
 * 문장 쪽을 앞에 둔다 — 사람이 확인해 적은 것이라 규칙 낱말보다 정확하다.
 * 규칙 낱말은 문장이 없거나 짧을 때 뒤를 채운다.
 *
 * @param {string|null} 문장  사람이 적어 준 한 문장 (없을 수 있다)
 * @param {string[]}    tags  규칙이 붙인 낱말
 * @param {string}      종목명
 * @param {number}      최대  몇 개까지
 */
export function 사업항목(문장, tags = [], 종목명 = "", 최대 = 4) {
  const 모음 = [];
  const 넣기 = (w) => {
    if (!w) return;
    const k = w.replace(/\s+/g, "");
    // 이미 있는 낱말에 먹히는 것은 넣지 않는다 — 제지 · 제지사업
    if (모음.some((x) => x.replace(/\s+/g, "") === k)) return;
    모음.push(w);
  };

  if (문장) {
    const { 몸통, 괄호 } = 괄호떼기(문장, 종목명);
    // 한국어는 주된 목적어가 앞에 온다. 뒤로 갈수록 곁가지라 둘까지만 본다 —
    // 한국타이어의 "…타이어를 제조해 … 고수익을 …" 에서 고수익이 딸려 왔다.
    for (const 덩이 of 목적어들(몸통).slice(0, 2)) for (const w of 쪼개기(덩이)) 넣기(w);
    for (const w of 괄호) 넣기(w);
  }
  // 규칙 낱말은 문장이 모자랄 때만 채운다.
  //
  // 규칙 낱말은 '이 테마에 왜 붙었나' 이지 '무슨 회사인가' 가 아니다. 테마마다
  // 다르기도 하다. 한솔제지는 제지·펄프에서는 인쇄용지·백판지로, 음식료에서는
  // 가공식품·라면으로 붙어 있다(자회사가 컵라면 종이용기를 만든다). 문장이
  // "제지(인쇄용지)를 생산하는…" 이라고 이미 밝혔으면 그것으로 충분하다.
  if (모음.length < 2) {
    for (const t of tags) {
      if (t === "작업지") continue;
      넣기(낱말다듬기(t));
    }
  }
  return 모음.slice(0, 최대);
}
