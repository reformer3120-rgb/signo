let pass = 0;
const fails = [];
for (const [label, text, id, want] of CASES) {
  const theme = byId[id];
  if (!theme) { fails.push(`${label} — 테마 ${id} 가 사전에 없다`); continue; }
  const { score, why } = scoreOne(text, theme);
  const got = score >= MIN_SCORE;
  if (got === want) {
    pass++;
  } else {
    fails.push(
      `${label}\n     기대 ${want ? "편입" : "제외"} · 실제 ${got ? "편입" : "제외"}` +
        ` (점수 ${score}${why.length ? ", 근거 " + why.join("/") : ""})`,
    );
  }
}

