  // 하나도 안 남았는데, 「LNG운반선 등 특수선을 건조하는 조선사로 …」 라는
  // 멀쩡한 편입 사유를 두고도 카드가 통째로 비었다.

  // 점수로 고르되, 늘어놓는 것은 원문 순서다
  const 매김 = 후보.map((s, i) => ({ s, i, v: 점수(s, i) }));

