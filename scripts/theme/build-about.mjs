    // 전에는 그냥 얹었다. 사람이 손본 것이라 믿을 만하다고 본 것인데,
    // 손보지 않은 것은 원문 발췌 그대로라서 원문의 온갖 찌꺼기가 검사 없이
    // 들어왔다. 개요에 남은 흠이 거의 다 이 경로였다.
    //   알파칩스 「집적회로ic.jpg 집적회로ic 팹리스(Fabless) 업체는 …」
