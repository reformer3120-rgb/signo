const 쪼개기 = (s) => s.split(/(?<=[다요][.])(?=[가-힣])/);

/**
 * 문장 뒤에 덧붙은 실적·군더더기를 떼어 낸다.
 *
 * 사업 설명 한 문장에 실적을 이어 붙이는 회사가 많다.
 *   "…인삼식품 제조업을 영위중이며, 2025년 6월말 현재 총자산 73,054백만원…"
 * 앞의 절반이 우리가 찾던 바로 그 문장인데, 실적이 붙었다는 이유로 통째로
 * 버리면 개요가 아예 안 선다. 실제로 대동고려삼은 원문에 쓸 만한 문장이
 * 이것 하나뿐이라 카드가 낱말만으로 섰다.
 *
 * 그래서 꼬리가 시작되는 쉼표에서 자른다. 앞에 온전한 절이 남을 때만.
 */
function 꼬리자르기(s) {
  let t = s.trim();

  // 실적이 시작되는 첫 쉼표에서 자른다. 뒤에 몇 절이 더 붙어 있어도
  // 거기부터는 다 실적이다.
  const 절 = t.split(",");
  const 실적 = /(총자산|자산총계|자기자본|납입자본금|매출액|영업이익|당기순이익|자본금은)/;
  const k = 절.findIndex((c, i) => i > 0 && 실적.test(c));
  if (k > 0) {
    const 앞 = 절.slice(0, k).join(",").trim();
    if (앞.length >= 30) t = 앞;
  }

  // 뒤가 잘려 나간 문장 — 마지막 쉼표 뒤가 서술어 없는 토막이면 버린다.
  //   케이비증권  "…주요사업으로 영위하고 있으며, 사업부문"
  const m = t.match(/^(.*),\s*([^,]{1,14})$/);
  if (m && !/(다|요|음|함|며|고|여)[.]?$/.test(m[2].trim()) && m[1].trim().length >= 30) {
    t = m[1].trim();
  }

  // 자르고 나서 "-며" 로 끝나면 종결어미를 새로 달아 준다
  if (/(으)?며$/.test(t)) t = 며닫기(t) ?? t;
  return t !== s.trim() ? t.replace(/[.]?$/, ".") : s;
}

/**
 * 너무 긴 문장을 줄인다 — 못 줄이면 버린다.
 *
 * 예전에는 한계에서 뭉텅 자르고 말줄임표를 붙였다. 그랬더니 전체 문장의
 * 11%(778개)가 「…특별한 경…」 처럼 도중에 끊겼다. 개요는 세 문장뿐이라
 * 그중 하나가 토막이면 카드가 통째로 못 쓰게 된다.
 *
 * 지금은 한계 안쪽의 절 경계에서 닫아 보고, 닫을 자리가 없으면 null 을
 * 돌려준다. 그 문장은 후보에서 빠지고 다음 문장이 자리를 메운다.
 * 잘린 문장을 보여 주느니 다른 문장을 보여 주는 편이 낫다.
 */
function 줄이기(t, 한계) {
  if (t.length <= 한계) return t;
  const 앞 = t.slice(0, 한계);
  // 뒤에서부터 절 경계를 찾는다. 문장 끝(다.)이 있으면 그게 가장 깨끗하다.
  const 끝 = 앞.match(/^([\s\S]*[다요][.])\s/);
  if (끝 && 끝[1].length >= 40) return 끝[1];
  // 쉼표가 없어도 닫는다. 「…영위하고 있으며 최근에는 …」 처럼 쉼표 없이
  // 이어지는 문장이 훨씬 많아, 쉼표를 요구하면 6,452문장이 통째로 버려진다.
  const m = 앞.match(/^([\s\S]*(?:으며|하며|이며|되며|하고 있으며))\s*[,]?\s/);
  if (m && m[1].length >= 40) {
    const 닫은것 = 며닫기(m[1]);
    if (닫은것) return 닫은것 + ".";
  }
  return null;
}

/**
 * 개요에 실을 문장이 아닌 것.
 *
 * 분류에 쓰는 ourSentences() 를 그대로 쓰지 않는다. 그쪽은 "이 문장이 분류
 * 근거가 되는가" 를 보느라 잣대가 훨씬 빡빡해서, 정작 개요로 가장 좋은
 * 첫 문장이 걸러졌다.
 *
 *   셀트리온  "당사는 생명공학기술을 기반으로 … 글로벌 생명공학기업입니다."
 *
 * 그래서 여기서는 문장만 받아 와 개요 잣대로 다시 거른다.
 */
function 버린다(s) {
  if (s.length < MIN_길이) return true;
  // 앞 문장에 매달린 토막 — 떼어 놓으면 뜻이 서지 않는다
  if (/^(또한|더불어|이에|그리고|한편|이러한|이와|아울러|반면|다만|따라서|특히|이를|그러나|이 중|그중)/.test(s)) return true;
  if (/^[를을은는이가와과의도에로]\s/.test(s)) return true;
  // 문장 앞이 잘려 나간 것 — "년에는 프리미엄 …" (앞의 2016 이 떨어졌다)
  if (/^(년|월|일|개|억|만|천)(에|은|는|을|이|부터|까지|가)/.test(s)) return true;
  // 사업계획은 버리지 않는다. 다만 알맹이가 있어야 한다.
  //
  // 처음에는 「하려는 일이지 하고 있는 일이 아니다」 며 계획을 통째로 걸렀다.
  // 그런데 개요에서 알고 싶은 것 중 하나가 바로 「무엇을 추진 중인가」 다.
  // 셀트리온이 ADC·다중 항체 같은 차세대 모달리티를 준비한다는 것은 이 회사를
  // 볼 때 아는 편이 나은 이야기다.
  //
  // 가르는 잣대는 계획이냐 아니냐가 아니라, 무엇을 언제 어디에 하겠다는
  // 말이 붙어 있느냐다. 붙어 있지 않으면 어느 회사 보고서에나 있는 다짐이다.
  //   남긴다  「2026년 상반기 3공장 준공을 목표로 …」   해와 시설이 있다
  //   버린다  「지속적인 성장을 목표로 노력하고 있다」   아무 말도 하지 않는다
  if (/노력하고 있|최선을 다하|기대(됩니다|된다|하고)|만전을 기하|매진하/.test(s)) return true;
  if (/할 예정|추진 (중|하고)|계획(이다|입니다|하고|을 가지고)|목표로 하|검토 중|나갈 (계획|방침)/.test(s)
      && !/20\d{2}|\d+억|\d+조|\d+%|\d+만|\d+개|[A-Z]{2,}|공장|라인|임상|허가|승인|증설|준공|착공|인수|상장|공모|특허/.test(s))
    return true;
  // 표를 한 줄로 풀어 놓은 것, 또는 표를 가리키는 말
  //
  // 쉼표 수만 보고 버리면 안 된다. 면허를 늘어놓는 문장은 원래 쉼표가 많다.
  //   케이비증권  "…투자매매업, 투자중개업, 투자자문업, 투자일임업, 신탁업,
  //                일반사모집합투자업의 금융투자업무 및 … 영위하고 있으며"
  // 표를 가리는 일은 looksTable() 의 조사 밀도가 이미 한다. 여기서는
  // 문장답게 끝나지도 않으면서 쉼표만 많은 것을 걸러 낸다.
  if ((s.match(/[,·]/g) ?? []).length > 6 && !/(다|요)[.]?$/.test(s.trim())) return true;
  if ((s.match(/[,·]/g) ?? []).length > 14) return true;
  // 빗금도 마찬가지다. "위탁/자산관리부문 … 주식/채권/파생상품 트레이딩" 처럼
  // 진짜 문장 안에서도 빗금은 흔히 쓰인다.
  if ((s.match(/\//g) ?? []).length >= 3 && !/(다|요)[.]?$/.test(s.trim())) return true;
  if (/대분류\s*중분류|사업부문\s*주요|구분\s*(품목|내용|주요)/.test(s)) return true;
  if (/다음과 같|아래와 같|하기와 같|참조하시기|기재를 생략|해당 사항 ?없/.test(s)) return true;
  // 사업보고서의 상투구 — 아무 회사에나 그대로 적혀 있어 개요가 되지 못한다
  if (/판매전략|영업전략|마케팅 전략|영업활동을 (진행|수행)|수익성 확보/.test(s)) return true;
  if (/^(지역별|부문별|사업부별|제품별|구분별)/.test(s)) return true;
  // 본문에 딸려 온 그림 파일 이름. 사업보고서 원문에는 그림이 파일명으로
  // 박혀 있어 그대로 문장 앞에 붙는다.
  //   라온로보틱스   「identity_1.jpg 사업의 개요 반도체 제조 라인은…」
  //   에이비엘바이오 「organisation process.jpg [Business Model] …」
  if (/\.(jpg|jpeg|png|gif|bmp)/i.test(s)) return true;
  // 괄호 짝이 안 맞는 것. 표를 한 줄로 풀어 놓았거나 소제목이 본문에 붙어
  // 번호 매김의 닫는 괄호만 남은 경우다.
  //   인포바인  「산업의 특성 1) 정보보호산업일반적으로 …」
  //   아이큐어  「및 사업부문의 구분 가) 영업개황 아이큐어주식회사(이하 …」
  if ((s.match(/[(]/g) ?? []).length !== (s.match(/[)]/g) ?? []).length) return true;
  // 정관의 목적사업 조항을 옮겨 놓은 것 — 개요가 아니라 법 문구다
  if (/각 ?호의 어느|하여서는 아니|의거 다음|정관에 따라|법률에 의거/.test(s)) return true;
  // 번호 매긴 조항의 꼬리가 붙은 것 — 「…원료 기재의 수입업 6.」
  if (/\s\d{1,2}[.]\s*$/.test(s)) return true;
  // 소제목만 잔뜩 붙고 알맹이가 없는 것
  if (/^\(?\d[).]\s*(영업|사업|회사)/.test(s)) return true;
  // 회계 기준을 설명하는 상투구. 어느 회사 보고서에나 거의 같은 말로 있어
  // 개요가 되지 못한다. 쉼표 잣대를 늦추자 이런 것들이 통과하기 시작했다.
  if (/수익을 창출하는 재화와 용역|보고부문|영업부문을 구분|경영의사결정|다각화 실태/.test(s)) return true;
  // 실적 — 재무제표 카드에 있다.
  //
  // 다만 문장 통째로 버리지는 않는다. 사업 설명 뒤에 실적을 덧붙인 꼴이
  // 흔한데, 그 하나뿐인 문장을 버리면 개요가 통째로 빈다.
  //   대동고려삼  "…인삼식품 제조업을 영위중이며, 2025년 6월말 현재
  //                총자산 73,054백만원…"
  // 꼬리를 떼는 일은 꼬리자르기() 가 먼저 한다. 여기까지 온 것은 문장이
  // 처음부터 실적 이야기인 경우다.
  if (/^[^,]{0,40}(매출액|영업이익|당기순이익)\s*[\d(]/.test(s)) return true;
  if (/매출액\s*[\d(]|영업이익\s*[\d(]|당기순이익|억\s?원(을|의)? ?(기록|달성)|조\s*[\d,]+\s*억|매출 ?비중은/.test(s)) return true;
  // 전년과 견주는 문장은 개요가 아니라 실적이다. 사업 설명인 척하며 끝에만
  // 붙는 것이 아니라 문장 전체가 증감 이야기인 것들이 여기 걸린다.
  //   삼성전기  "카메라모듈의 평균판매가격도 전년 대비 14.0% 상승했다."
  if (/전년\s?(동기\s?)?대비/.test(s)) return true;
  if (/평균판매가격|판매가격(은|이|도)|판매관리비|경상개발비|영업이익은/.test(s)) return true;
  // 지역별로 하나씩 늘어놓은 문장 — 여럿 중 한 토막이라 떼어 놓으면 뜻이 없다.
  //   삼성전자  "중동ㆍ아프리카에는 SGE(UAE) … 총 21개 법인이 운영되고 있다."
  if (/^(국내|해외|아시아|유럽|미주|북미|남미|중남미|중동|아프리카|중국|일본|미국|동남아|오세아니아|국내외)[ㆍ·\/]?[가-힣]{0,6}에(는|서는)\s/.test(s)
      && /\d+\s?개.*(법인|지사|사무소|공장)|(법인|지사|사무소)(을|를|이|가)? ?(운영|두고)/.test(s)) return true;
  // 지분·주주·공시 절차 — 개요가 아니라 공시다
  if (/지분(을|율은|율이)\s|주주총회|이사회\s?결의|공시(하였|했)|정관|기업집단|공정거래법/.test(s)) return true;
  if (/사업의 중단|중단을 결정|영업정지|감사의견/.test(s)) return true;
  // 연결 범위가 바뀌었다는 공시 — 회사가 무엇을 하는지가 아니다.
  //   GS 「… (주)어바웃펫 지분매각이 완료되어 연결대상 종속기업에서 제외되었습니다.⑤ …」
  if (/연결(대상)? ?종속(기업|회사)에서 (제외|편입)|지분매각이 완료|연결 ?범위/.test(s)) return true;
  // 앞이 잘려 나간 토막 — 구두점으로 시작하면 문장이 아니다.
  //   시프트업 「, , IP 이외에도 신규 IP의 개발 및 확보를 …」
  if (/^[,·.;:)\]}\/%]/.test(s.trim())) return true;
  // 생산능력·가동률·매출 실적 — 숫자는 재무제표 카드에 있다.
  //   롯데웰푸드 「(매출 실적) 2025년 1~12월 회사의 매출액은 3,282,857(백만원)다.」
  //   휴스틸     「2025년 전체 생산능력은 1,151,750톤, 생산실적은 412,499톤이며 …」
  if (/생산능력|생산실적|가동률|가동율|매출 ?실적[)）]|매출액은\s*[\d,]{5,}/.test(s)) return true;
  // 다른 절을 가리키는 안내문 — 무엇을 하는 회사인지는 한 마디도 없다.
  //   일동제약  「주요 제품 및 서비스를 참고하여 주시기 바랍니다.」
  //   인선이엔티 「… 아래 실적 요약표를 참조해 주시기 바랍니다.」
  if (/참고하여 주시기|참조해 주시기|참고하시기 바랍|참조하시기 바랍|참고 ?바랍니다|상세히 기재되어 있/.test(s)) return true;
  // 표에서 항목 번호가 문장에 끌려 들어온 것
  if (/[①-⑮⒜-⒵]/.test(s)) return true;
  // 신용평가·자금조달 이력 — 개요가 아니라 공시 항목이다
  if (/신용평가|회사채 ?및|기업어음|무보증사채|신용등급/.test(s)) return true;
  // 다짐으로 끝나는 문장. 어느 회사 보고서에나 있고 하는 일을 말하지 않는다.
  //   케이뱅크 「앞으로도 더 혁신적이고 안정적인 서비스를 … 진화해나갈 것이다.」
  if (/(나갈|할|될) 것이다[.]?$/.test(s) && !/20\d{2}|\d+억|\d+조|[A-Z]{2,}|공장|임상|허가/.test(s)) return true;
  // 내 얘기가 아니라 업계 얘기
  if (/전방산업|후방산업|시장 ?규모|업황|시황|경쟁(사|업체)|점유율은|산업은|산업이 |전망(됩니다|된다|이다|을 살펴|이 밝)/.test(s)) return true;
  // 업종 일반론
  if (/^(지주회사|리츠|이 산업|해당 산업|본 산업)(는|은|이란)/.test(s)) return true;
  // 남의 회사가 주어인 문장 — 이 종목이 무엇을 하는지가 아니다.
  //   피제이메탈 「종속회사 ㈜피제이이앤에스는 2023년 신설된 법인으로 …」
  //   휴젤       「연결대상 종속법인인 ㈜아크로스는 HA필러를 …」
  // 종목명이 든 문장은 건드리지 않는다. 회사 이름에 ㈜가 붙은 곳이 많다.
  if (/(종속(회사|기업|법인)|자회사|계열(회사|사))(인|의)? ?[^,]{0,20}(㈜|\(주\)|주식회사)?[가-힣A-Za-z0-9]{2,15}(는|은|이|가)\s/.test(s)) return true;
  return false;
}

/**
 * 문장의 갈래.
 *
 * 개요 세 줄이 다 「무슨 회사인가」 면 읽을 것이 없다. 셀트리온이 그랬다 —
 * 소개 두 줄에 합병 한 줄이고, 정작 「2023년 짐펜트라의 미국 FDA 신약 허가를
 * 획득하며 글로벌 신약 시장에 본격 진출」 이 점수에 밀려 빠졌다.
 *
 * 개요에서 알고 싶은 것은 넷이다 — 무슨 회사인가, 어떻게 여기까지 왔나,
 * 지금 무엇을 하고 있나, 무엇을 만드나. 갈래를 나눠 한 줄씩 뽑는다.
 */
function 갈래(s) {
  // 「제품이나 이슈」 와 「사업계획」 은 다른 이야기다. 하나는 이미 일어난
  // 것이고 하나는 앞으로 할 것이다. 한 줄씩 따로 준다.
  if (/할 예정|계획(이다|입니다|하고|을 가지고|을 세)|목표로 하|향후|추진 (중|하고|할)|나갈 (계획|방침|예정)/.test(s))
    return "계획";
  if (변곡(s)) return "성과";
  if (/설립(되|하|된|일)|창립|합병(하|되|을|하여)|상장(하|되)|전환(하였|했)/.test(s)) return "연혁";
  if (/영위하|주요 ?(목적 )?사업|주된 사업|기업이다|기업입니다|전문기업|하는 회사/.test(s)) return "소개";
  return "그밖";
}

/**
 * 이 회사의 앞날을 바꿀 만한 이야기인가.
 *
 * 「사건」 이라고만 두었더니 창업 이래의 자잘한 이력까지 다 걸렸다. 개요에
 * 넣고 싶은 것은 아무 사건이 아니라 변곡점이다 — 새 제품, 새 시장, 큰 투자,
 * 그리고 지금 추진 중인 계획.
 */
function 변곡(s) {
  return /(신약|신제품|신규 ?사업|차세대|FDA|식약처|품목 ?허가|허가를? ?(획득|취득|받)|승인(을 받|받았|을 획득)|임상 ?\d상|기술이전|기술수출|공급 ?계약|수주(하였|했|를 받|를 확보)|인수를? ?(완료|하였|했)|합병을? ?(완료|하였)|증설|준공|착공|신공장|진출(하였|했|하며|할)|출시(하였|했|할|를 앞)|전환(을 완료|하였))/.test(s)
    || /(할 예정|추진 (중|하고)|계획|목표로)/.test(s);
}

/**
 * 남의 회사가 주어인 문장인가.
 *
 * 「종속회사」 같은 말 없이 이름만 덜렁 나오는 것들이 남았다.
 *   한화오션 「DSME Kazakhstan LLP는 해양프로젝트 계약 관리를 …」
 *   한진칼   「㈜대한항공은 여객사업, 화물사업을 …」
 * 회사 꼴이 붙은 이름이 주어인데 그 안에 종목명이 없으면 남의 회사다.
 * 종목명이 들어 있으면 제 얘기다 — 와이씨켐이 「와이씨켐 주식회사(이하
 * '회사')는 2001년 설립과 함께 …」 로 시작한다.
 */
function 남의회사(s, name) {
  const m = s.match(/^([^,.]{2,40}?)\s*(는|은|이|가)\s/);
  if (!m) return false;
  const 주어 = m[1];
  if (name && 주어.includes(name)) return false;
  return /㈜|\(주\)|주식회사|Co[.,]| ?Ltd|Inc[.,]?|LLC|LLP|GmbH|Pte|Pty|유한공사/i.test(주어);
}

/** 개요다운 문장일수록 높다 */
function 점수(s, i) {
  let v = 0;
  // 본업을 말하는 문장
  if (/주요 ?(목적 )?사업|주된 사업|영위하|주력(은|으로|제품)|본업|주요 제품/.test(s)) v += 4;
  // 종속회사 소개는 모회사가 무엇을 하는지가 아니다 — 달리 쓸 것이 없을 때만 쓴다
  if (/종속(회사|기업)(인|는|의)|자회사(인|는)/.test(s)) v -= 3;
  // 종속회사 이름이 주어인 문장 — 이 종목이 무엇을 하는지가 아니다
  if (/(LLP|유한공사|Inc\.|Corp\.|Co\.,? ?Ltd)/.test(s)) v -= 3;
  if (/설립(되|하|된|일)|창립|합병(하|되|을|하여)|상장(하|되)/.test(s)) v += 3;
  if (/제품|서비스|솔루션|생산|제조|개발|공급|판매/.test(s)) v += 2;
  if (/당사(는|의|가)|연결회사|자사/.test(s)) v += 2;
  // 앞날을 바꿀 만한 이야기 — 개요에서 가장 알고 싶은 대목이다.
  //
  // 같은 변곡이라도 무게가 다르다. 새 제품·새 시장으로 가는 이야기가
  // 공장을 늘렸다는 이야기보다 이 회사를 더 많이 설명한다.
  //   셀트리온  「짐펜트라의 미국 FDA 신약 허가 … 글로벌 신약 시장 진출」
  //             「브랜치버그 공장 인수를 완료하였으며 …」          보다 앞선다
  if (/신약|신제품|신규 ?사업|차세대|새로운 사업|사업 ?다각화|진출(하였|했|하며|할)|전환(을 완료|하였|했)/.test(s)) v += 4;
  else if (변곡(s)) v += 2;
  // 알맹이 없는 진행형은 내린다.
  //
  // 「…을 지속하고 있습니다」 「…을 강화하고 있습니다」 는 무엇이 언제 있었는지
  // 말하지 않는다. 같은 자리를 놓고 다투면 사실을 적은 쪽이 나아야 한다.
  //   내린다  「후속 파이프라인을 확보하기 위한 노력을 지속하는 한편 …」
  //   올린다  「2023년에는 … 짐펜트라(CT-P13 SC)의 미국 FDA 신약 허가를 획득하며 …」
  if (/(지속|강화|확대|집중|주력)하(고 있|는 한편|여 오)/.test(s) && !/20\d{2}년/.test(s)) v -= 3;
  // 최근 일일수록 낫다. 창업기 이력보다 지금 무엇을 하고 있는가가 궁금하다.
  //   셀트리온  램시마(창업기) 보다 짐펜트라 미국 FDA 신약 허가(2023) 쪽
  const 해 = (s.match(/20(\d{2})년/g) ?? []).map((x) => Number(x.slice(0, 4)));
  if (해.length && Math.max(...해) >= new Date().getUTCFullYear() - 4) v += 3;
  // 사업보고서는 앞에서 자기 소개를 하고 뒤로 갈수록 곁가지로 샌다
  v += i < 3 ? 2 : i < 8 ? 1 : 0;
  // 너무 짧으면 알맹이가 없고, 너무 길면 잘라야 한다
  v += s.length < 40 ? -2 : s.length <= MAX_길이 ? 1 : -1;
  const 쉼표 = (s.match(/[,·]/g) ?? []).length;
  if (쉼표 > 3) v -= 2;
  return v;
}

/**
 * 같은 말을 두 번 하지 않게 한다.
 *
 * 사업보고서는 한 단락 안에서 같은 문구를 되풀이하는 일이 잦다. 낱말을 견줘
 * 절반 넘게 겹치면 뒤엣것을 버린다.
 */
function 겹치나(a, b) {
  const A = new Set(a.replace(/[^가-힣0-9a-zA-Z ]/g, " ").split(/\s+/).filter((w) => w.length > 1));
  const B = a === b ? A : new Set(b.replace(/[^가-힣0-9a-zA-Z ]/g, " ").split(/\s+/).filter((w) => w.length > 1));
  if (!A.size || !B.size) return false;
  let n = 0;
  for (const w of B) if (A.has(w)) n++;
  return n / Math.min(A.size, B.size) > 0.5;
}

