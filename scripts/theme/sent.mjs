// 사업보고서 문장을 화면에 실을 꼴로 다듬는다.
//
// 원문은 "…생산하고 있습니다" 인데 사람이 적어 준 문장은 "…생산한다" 다.
// 한 화면에 섞이면 눈에 걸리므로 어미만 맞춘다. 뜻은 건드리지 않는다.
//
// build-data.mjs(편입 사유)와 build-about.mjs(기업 개요)가 같이 쓴다.

const 어미 = [
  [/하였습니다\.?$/, "했다."], [/되었습니다\.?$/, "됐다."],
  [/있습니다\.?$/, "있다."], [/없습니다\.?$/, "없다."],
  [/습니다\.?$/, "다."],
  [/합니다\.?$/, "한다."], [/됩니다\.?$/, "된다."],
];

/** 받침이 있으면 "이다", 없으면 "다" — 기업입니다→기업이다 · 회사입니다→회사다 */
function 받침(ch) {
  const c = (ch ?? "").charCodeAt(0) - 0xac00;
  return c >= 0 && c < 11172 && c % 28 !== 0;
}

export function 평서문(s) {
  // "…영위하고 있습니다.3) 건설업" — 다음 절 머리가 붙어 온 것을 떼어 낸다
  let t = s.trim().replace(/([다요])\.\s*\d+[).]?\s*\S*$/, "$1.").trim();
  const m = t.match(/^(.*?)입니다\.?$/);
  if (m) {
    const h = m[1].trim();
    return h + (받침(h[h.length - 1]) ? "이다." : "다.");
  }
  for (const [re, to] of 어미) if (re.test(t)) return t.replace(re, to);
  return /[.!?…]$/.test(t) ? t : t + ".";
}

/**
 * "-며/-으며" 로 이어지던 절을 문장으로 닫는다.
 *
 *   "…금융투자업무를 주요사업으로 영위하고 있으며"  →  "…영위하고 있다."
 *
 * 뒤가 잘려 나간 문장을 살려 쓸 때 필요하다. 원문에서 뒷절만 버리면
 * 앞절이 종결어미 없이 남는다.
 */
export function 며닫기(h) {
  const 줄기 = h.trim().replace(/[,·]$/, "").replace(/(으)?며$/, "");
  // 형용사와 계사는 "-는다" 를 받지 않는다.
  //   있으며 → 있다 (있는다 ×)   없으며 → 없다
  //   영위중이며 → 영위중이다 (영위중인다 ×)
  if (/(있|없)$/.test(줄기)) return 줄기 + "다";
  if (/이$/.test(줄기)) return 줄기 + "다";
  const 끝 = 줄기.charCodeAt(줄기.length - 1) - 0xac00;
  if (끝 < 0 || 끝 >= 11172) return null;
  if (끝 % 28 !== 0) return 줄기 + "는다";                                  // 받침 있음
  return 줄기.slice(0, -1) + String.fromCharCode(0xac00 + 끝 + 4) + "다";   // ㄴ 받침(4)
}
