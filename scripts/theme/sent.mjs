// 사업보고서 문장을 화면에 실을 꼴로 다듬는다.
//
// 원문은 "…생산하고 있습니다" 인데 사람이 적어 준 문장은 "…생산한다" 다.
// 한 화면에 섞이면 눈에 걸리므로 어미만 맞춘다. 뜻은 건드리지 않는다.
//
// build-data.mjs(편입 사유)와 build-about.mjs(기업 개요)가 같이 쓴다.

/**
 * 「-ㄴ다/-는다」 를 받지 않는 말들.
 *
 * 형용사와 계사는 「-다」 로 끝난다. 이걸 가리지 않아 개요에 이런 것들이
 * 실려 있었다.
 *   가능한다 · 다양한다 · 중요한다 · 필요한다   (가능하다 · 다양하다 …)
 * 「하」 로 끝난다고 다 동사가 아니다 — 생산하며는 생산한다가 맞고
 * 다양하며는 다양하다가 맞다. 가릴 길이 없어 흔한 형용사를 적어 둔다.
 */
const 형용사 =
  /(가능|불가능|필요|불필요|중요|다양|우수|충분|불충분|풍부|저렴|안전|위험|적합|부적합|유리|불리|강력|활발|동일|유사|원활|용이|미미|급격|정확|정밀|치열|취약|열악|양호|미흡|저조|과도|광범위|다각|중대|막대|심각|긴밀|밀접|명확|단순|복잡|투명|견고|탄탄|저조|무난|시급|절실|당연|분명)하$/;

/**
 * 과거를 나타내는 꼬리 — 「출발하였는다」 가 아니라 「출발하였다」 다.
 *
 * 았·었·였 만 보다가 줄어든 꼴을 놓쳤다. 「이어왔으며」 가 「이어왔는다」 로,
 * 「개발했으며」 가 「개발했는다」 로 굳어 화면에 나갔다(42문장).
 * 한국어에서 ㅆ 받침으로 끝나는 말끝은 과거다 — 왔·했·췄·줬·냈 모두 걸린다.
 */
const 과거 = (줄기) => {
  const c = (줄기 ?? "").charCodeAt((줄기 ?? "").length - 1) - 0xac00;
  return c >= 0 && c < 11172 && c % 28 === 20; // ㅆ 받침
};

const 어미 = [
  [/하였습니다\.?$/, "했다."], [/되었습니다\.?$/, "됐다."],
  [/있습니다\.?$/, "있다."], [/없습니다\.?$/, "없다."],
  [/습니다\.?$/, "다."],
  [/합니다\.?$/, "한다."], [/됩니다\.?$/, "된다."],
];

/** 받침이 있으면 "이다", 없으면 "다" — 기업입니다→기업이다 · 회사입니다→회사다 */
function 받침(ch) {
  const c = (ch ?? "").charCodeAt(0) - 0xac00;
  return c >= 0 && c < 11172 && c % 28 !== 0;
}

export function 평서문(s) {
  // "…영위하고 있습니다.3) 건설업" — 다음 절 머리가 붙어 온 것을 떼어 낸다
  let t = s.trim().replace(/([다요])\.\s*\d+[).]?\s*\S*$/, "$1.").trim();
  // 이미 잘못 굳어 있는 것을 고친다. themes.json 의 편입 사유는 예전 잣대로
  // 만들어져 「출발하였는다」 「중요한다」 가 남아 있다.
  t = t.replace(/([가-힣])는다([.]?)$/, (전체, 글, 점) => (과거(글) ? 글 + "다" + 점 : 전체));
  {
    const m = t.match(/^(.*?)([가-힣]{2,6})한다([.]?)$/);
    if (m && 형용사.test(m[2] + "하")) t = m[1] + m[2] + "하다" + m[3];
  }
  const m = t.match(/^(.*?)입니다\.?$/);
  if (m) {
    const h = m[1].trim();
    return h + (받침(h[h.length - 1]) ? "이다." : "다.");
  }
  // 「가능합니다」 는 「가능한다」 가 아니라 「가능하다」 다
  const 형 = t.match(/^(.*?)합니다\.?$/);
  if (형 && 형용사.test(형[1] + "하")) return 형[1] + "하다.";
  for (const [re, to] of 어미) if (re.test(t)) return t.replace(re, to);
  return /[.!?…]$/.test(t) ? t : t + ".";
}

/**
 * "-며/-으며" 로 이어지던 절을 문장으로 닫는다.
 *
 *   "…금융투자업무를 주요사업으로 영위하고 있으며"  →  "…영위하고 있다."
 *
 * 뒤가 잘려 나간 문장을 살려 쓸 때 필요하다. 원문에서 뒷절만 버리면
 * 앞절이 종결어미 없이 남는다.
 */
export function 며닫기(h) {
  const 줄기 = h.trim().replace(/[,·]$/, "").replace(/(으)?며$/, "");
  // 형용사와 계사는 "-는다" 를 받지 않는다.
  //   있으며 → 있다 (있는다 ×)   없으며 → 없다
  //   영위중이며 → 영위중이다 (영위중인다 ×)
  if (/(있|없)$/.test(줄기)) return 줄기 + "다";
  if (/이$/.test(줄기)) return 줄기 + "다";
  // 과거형은 「-는다」 를 받지 않는다 — 출발하였다 (출발하였는다 ×)
  if (과거(줄기)) return 줄기 + "다";
  // 형용사도 마찬가지다 — 다양하다 (다양한다 ×)
  if (형용사.test(줄기)) return 줄기 + "다";
  const 끝 = 줄기.charCodeAt(줄기.length - 1) - 0xac00;
  if (끝 < 0 || 끝 >= 11172) return null;
  if (끝 % 28 !== 0) return 줄기 + "는다";                                  // 받침 있음
  return 줄기.slice(0, -1) + String.fromCharCode(0xac00 + 끝 + 4) + "다";   // ㄴ 받침(4)
}
